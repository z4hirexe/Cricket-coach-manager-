"""Extracts gameplay data from cricketer.glb for the Kotlin delivery planner and makes travelling clips 'in place'.

usage: clip_data.py src_cricketer.glb out_cricketer.glb out_ClipData.kt

* Samples (in model space, 24 fps) the hand paths the ball must follow (bowler release, throw, catch, keeper collect/stump),
  the bat sweet spot at each shot's impact frame, the front pad for LBWs and the front foot at delivery-stride landing.
* bowl_fast / bowl_spin / field_throw / field_dive carry root motion (hips travel up to 1 m).  When the next clip starts the
  body would snap back to the actor origin.  We subtract that travel from the hips channel (so every clip starts and ends at
  the origin) and export it as a drift table; the planner moves the actor by exactly the same amount instead.
  Net world motion is identical, but there are no more pops between clips.
"""
import sys, struct, numpy as np, pygltflib
sys.path.insert(0, __import__("os").path.dirname(__file__))
from preview import Model

src, out_glb, out_kt = sys.argv[1:4]
P = Model(src)
N = {n.name: i for i, n in enumerate(P.g.nodes)}
DUR = {a.name: float(max(P.acc(s.input).max() for s in a.samplers)) for a in P.g.animations}
FPS = 24

def world(clip, t): return P.world(P.anim_index(clip), t)
def pt(W, node, local=(0, 0, 0)): return (W[N[node]] @ np.array([*local, 1.0]))[:3]

def samples(clip, fn, t1=None):
    t1 = DUR[clip] if t1 is None else t1
    ts = np.arange(0, t1 + 1e-6, 1 / FPS)
    return np.array([fn(world(clip, t)) for t in ts])

IMPACT = {"bat_defend": .55, "bat_cover_drive": .55, "bat_straight_drive": .55, "bat_pull": .5, "bat_hook": .5, "bat_cut": .5,
          "bat_sweep": .6, "bat_reverse_sweep": .6, "bat_loft": .55, "bat_miss": .55, "bat_leave": .55}
SWEET = {k: pt(world(k, t), "bat", (0, 0.55, 0.02)) for k, t in IMPACT.items()}
Wm = world("bat_miss", .55)
PAD = pt(Wm, "shin_L") * 0.55 + pt(Wm, "foot_L") * 0.45 + np.array([0.0, 0.0, 0.0])
FOOT_LAND = {"bowl_fast": pt(world("bowl_fast", 1.58), "foot_L"), "bowl_spin": pt(world("bowl_spin", 1.175), "foot_L")}
REL = {"bowl_fast": 1.68, "bowl_spin": 1.30}

mid = lambda W: (pt(W, "hand_L") + pt(W, "hand_R")) / 2
handR = lambda W: pt(W, "hand_R", (0, -0.06, 0.02))
HANDS = {
    "run": samples("run", handR), "bowl_fast": samples("bowl_fast", handR, REL["bowl_fast"]), "bowl_spin": samples("bowl_spin", handR, REL["bowl_spin"]),
    "field_throw": samples("field_throw", handR), "field_catch": samples("field_catch", mid), "keep_collect": samples("keep_collect", mid),
    "keep_stump": samples("keep_stump", mid), "idle": samples("idle", handR), "field_ready": samples("field_ready", mid), "walk": samples("walk", handR),
    "celebrate": samples("celebrate", handR), "appeal": samples("appeal", handR), "keep_crouch": samples("keep_crouch", mid),
}

# ---- root motion -> drift tables + in-place patch
g = pygltflib.GLTF2().load(src); blob = bytearray(g.binary_blob())
DRIFT = {}
for clip in ("bowl_fast", "bowl_spin", "field_throw", "field_dive"):
    a = next(x for x in g.animations if x.name == clip)
    for ch in a.channels:
        if ch.target.path != "translation" or g.nodes[ch.target.node].name != "hips": continue
        s = a.samplers[ch.sampler]; ti = P.acc(s.input).astype(float)
        acc = g.accessors[s.output]; bv = g.bufferViews[acc.bufferView]
        assert acc.componentType == 5126 and acc.type == "VEC3" and not bv.byteStride
        off = bv.byteOffset + (acc.byteOffset or 0)
        v = np.frombuffer(bytes(blob[off:off + acc.count * 12]), np.float32).reshape(-1, 3).copy()
        d = v[:, [0, 2]] - v[0, [0, 2]]
        if np.abs(d).max() < 1e-4: print("already in place:", clip); continue
        v[:, 0] -= d[:, 0]; v[:, 2] -= d[:, 1]
        blob[off:off + acc.count * 12] = v.astype(np.float32).tobytes()
        if acc.min is not None: acc.min = [float(x) for x in v.min(0)]
        if acc.max is not None: acc.max = [float(x) for x in v.max(0)]
        ts = np.arange(0, ti[-1] + 1e-6, 1 / FPS)
        DRIFT[clip] = np.stack([np.interp(ts, ti, d[:, 0]), np.interp(ts, ti, d[:, 1])], 1)
        print("patched", clip, "travel", np.round(d[-1], 3))
g.set_binary_blob(bytes(blob)); g.save_binary(out_glb)

# ---- Kotlin
def fa(arr): return "floatArrayOf(" + ", ".join(f"{x:.3f}f" for x in np.asarray(arr).ravel()) + ")"
L = ["package com.cricketcoach.manager.render3d", "",
     "/* GENERATED by tools/assets/clip_data.py from cricketer.glb - do not edit by hand. Model space: +z forward, +y up, right hand at -x. */",
     "object ClipData {", f"    const val FPS = {FPS}f",
     "    val DUR = mapOf(" + ", ".join(f'"{k}" to {v:.3f}f' for k, v in DUR.items()) + ")",
     "    val IMPACT = mapOf(" + ", ".join(f'"{k}" to {v}f' for k, v in IMPACT.items()) + ")",
     "    /** bat sweet spot (model space) at the impact frame of each shot */",
     "    val SWEET = mapOf(" + ", ".join(f'"{k}" to {fa(v)}' for k, v in SWEET.items()) + ")",
     f"    /** front pad (model space) at the bat_miss impact frame - LBW target */\n    val PAD = {fa(PAD)}",
     "    /** front foot (model space) when it lands in the delivery stride, and the clip time of that landing / of release */",
     "    val FOOT_LAND = mapOf(" + ", ".join(f'"{k}" to {fa(v)}' for k, v in FOOT_LAND.items()) + ")",
     '    val LAND_T = mapOf("bowl_fast" to 1.58f, "bowl_spin" to 1.175f)',
     "    val REL_T = mapOf(" + ", ".join(f'"{k}" to {v}f' for k, v in REL.items()) + ")",
     "    /** hand path (model space, xyz per 1/FPS s) - the ball rides in these hands */",
     "    val HAND = mapOf(" + ",\n        ".join(f'"{k}" to {fa(v)}' for k, v in HANDS.items()) + ")",
     "    /** root travel removed from the clip (model-space x,z per 1/FPS s); the planner moves the actor by this instead */",
     "    val DRIFT = mapOf(" + ",\n        ".join(f'"{k}" to {fa(v)}' for k, v in DRIFT.items()) + ")",
     "",
     "    private fun sample(a: FloatArray, stride: Int, t: Float, loop: Boolean, out: FloatArray) {",
     "        val n = a.size / stride; if (n == 0) { out.fill(0f); return }",
     "        var f = t * FPS; if (loop) { f %= (n - 1).coerceAtLeast(1).toFloat(); if (f < 0) f += (n - 1) }",
     "        f = f.coerceIn(0f, (n - 1).toFloat()); val i = f.toInt().coerceAtMost(n - 2).coerceAtLeast(0); val u = if (n < 2) 0f else f - i",
     "        for (k in 0 until stride) out[k] = if (n < 2) a[k] else a[i * stride + k] * (1 - u) + a[(i + 1) * stride + k] * u",
     "    }",
     "    fun hand(clip: String, t: Float, out: FloatArray, loop: Boolean = false): Boolean { val a = HAND[clip] ?: return false; sample(a, 3, t, loop, out); return true }",
     "    /** model-space (x,z) root travel of [clip] at clip time t (0,0 for clips without travel) */",
     "    fun drift(clip: String, t: Float, out: FloatArray) { val a = DRIFT[clip]; if (a == null) { out[0] = 0f; out[1] = 0f } else sample(a, 2, t, false, out) }",
     "}", ""]
open(out_kt, "w").write("\n".join(L))
print("SWEET", {k: np.round(v, 3).tolist() for k, v in SWEET.items()}); print("PAD", np.round(PAD, 3), "FOOT", {k: np.round(v, 3) for k, v in FOOT_LAND.items()})
print("kt bytes", len(open(out_kt).read()))
